-- Owner-approved high-margin pricing, additive catalog refresh.
UPDATE dbo.TblPlan
SET MonthlyAiReplies=CASE Code WHEN N'FREE' THEN 30 WHEN N'STARTER' THEN 1000
 WHEN N'PRO' THEN 3000 WHEN N'BUSINESS' THEN 8000 END,
 MaxActiveKnowledgeItems=CASE Code WHEN N'FREE' THEN 50 WHEN N'STARTER' THEN 100
 WHEN N'PRO' THEN 400 WHEN N'BUSINESS' THEN 1200 END,
 MonthlyPriceAmount=CASE Code WHEN N'FREE' THEN 0 WHEN N'STARTER' THEN 1490
 WHEN N'PRO' THEN 3490 WHEN N'BUSINESS' THEN 8490 END,
 UpdatedAtUtc=SYSUTCDATETIME()
WHERE Code IN (N'FREE',N'STARTER',N'PRO',N'BUSINESS');
GO

-- Activate agreed Pricing V1 plan quotas/prices. Existing subscription IDs and payment records remain unchanged.
UPDATE dbo.TblPlan
SET MonthlyAiReplies=CASE Code WHEN N'FREE' THEN 30 WHEN N'STARTER' THEN 750
 WHEN N'PRO' THEN 2500 WHEN N'BUSINESS' THEN 6000 END,
 MaxWhatsAppConnections=1,
 MaxAgents=CASE Code WHEN N'FREE' THEN 1 WHEN N'STARTER' THEN 1
 WHEN N'PRO' THEN 3 WHEN N'BUSINESS' THEN 8 END,
 MaxActiveKnowledgeItems=CASE Code WHEN N'FREE' THEN 50 WHEN N'STARTER' THEN 200
 WHEN N'PRO' THEN 500 WHEN N'BUSINESS' THEN 2000 END,
 MonthlyPriceAmount=CASE Code WHEN N'FREE' THEN 0 WHEN N'STARTER' THEN 299
 WHEN N'PRO' THEN 599 WHEN N'BUSINESS' THEN 1199 END,
 UpdatedAtUtc=SYSUTCDATETIME()
WHERE Code IN (N'FREE',N'STARTER',N'PRO',N'BUSINESS');
GO
